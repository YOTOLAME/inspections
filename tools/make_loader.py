#!/usr/bin/env python3
"""Generate review-loader.js and checklists.txt (for AI assistants that cannot run code on attached files, e.g. Copilot).

The AI writes a small HTML file:
    <script>window.TEPA_REPORT = {"inspection": <inspection.json>, "mapping": <mapping>};</script>
    <script src="https://yotolame.github.io/inspections/review-loader.js"></script>
saved in the unzipped capture folder (photos next to it or in photos/). The loader builds the same review page
as tools/build_review.py (same checks, same data), with the photos read from the folder.

Usage: python3 -I tools/make_loader.py <repo dir>   -> writes <repo>/review-loader.js and <repo>/checklists.txt
"""
import json, os, sys
repo = sys.argv[1]
tools = os.path.join(repo, 'tools')
sys.path.insert(0, tools)
import build_checklists
tmp = os.path.join(tools, '.loader.tmp.json')
build_checklists.main(repo, tmp)
checklists = json.load(open(tmp, encoding='utf-8')); os.remove(tmp)
template = open(os.path.join(tools, 'review_template.html'), encoding='utf-8').read()
assert template.count('__REVIEW_DATA__') == 1

PHOTO_FALLBACK = """<script>
document.addEventListener('error', function (e) {
  var t = e.target;
  if (!t || t.tagName !== 'IMG') { return; }
  var s = t.getAttribute('src') || '';
  if (s.indexOf('data:') === 0 || s.indexOf('blob:') === 0) { return; }
  if (!t.getAttribute('data-r') && s.indexOf('/') < 0) { t.setAttribute('data-r', '1'); t.setAttribute('src', 'photos/' + s); return; }
  t.setAttribute('alt', 'Missing photo: ' + s.replace(/^photos\\//, '') + ' - save this HTML file in the unzipped capture folder');
  t.style.outline = '2px solid #8a2b1f';
}, true);
</script>
"""
assert template.count('</body>') == 1
template = template.replace('</body>', PHOTO_FALLBACK + '</body>')

# text list of all checklists for the AI
lines = ['CHECKLIST TEMPLATES AND QUESTIONS', 'Use the exact "form" file name and question number "q" in the mapping.', '']
for t in checklists:
    lines.append('=' * 70)
    lines.append('FORM: %s | %s | short name: %s | %d questions' % (t['form'], t['title'], t['shortName'], t['questionCount']))
    for s in t['sections']:
        lines.append('## ' + s['title'])
        for q in s['questions']:
            lines.append('%s  %s' % (q['q'], q['text']))
    lines.append('')
open(os.path.join(repo, 'checklists.txt'), 'w', encoding='utf-8').write('\n'.join(lines))

JS = r"""/* review-loader.js - generated by tools/make_loader.py, do not edit. ES5. */
(function () {
  var CHECKLISTS = __CHECKLISTS__;
  var TEMPLATE = __TEMPLATE__;

  function clone(o) { return JSON.parse(JSON.stringify(o)); }
  function trim(s) { return String(s == null ? '' : s).replace(/^\s+|\s+$/g, ''); }
  function base(p) { p = String(p || ''); var i = p.lastIndexOf('/'); return i >= 0 ? p.substr(i + 1) : p; }
  function hash(s) { var h = 5381, i; for (i = 0; i < s.length; i++) { h = ((h << 5) + h + s.charCodeAt(i)) | 0; } return (h >>> 0).toString(36); }

  /* Same logic and checks as tools/build_review.py main() */
  function build(R) {
    var insp = R.inspection || {}, mp = R.mapping || {}, errors = [], i, k;
    var all = {}; for (i = 0; i < CHECKLISTS.length; i++) { all[CHECKLISTS[i].form] = CHECKLISTS[i]; }
    var obs = {}, obsNos = []; var ol = insp.observations || [];
    for (i = 0; i < ol.length; i++) { obs[ol[i].no] = ol[i]; obsNos.push(ol[i].no); }
    var templates = [], qsets = {}, byform = {};
    var tl = mp.templates || [];
    for (i = 0; i < tl.length; i++) {
      var f = tl[i];
      if (!all[f]) { errors.push('unknown template ' + f); continue; }
      var t = clone(all[f]); t.items = {}; t._order = [];
      templates.push(t); byform[f] = t;
      var qs = {}; for (var s = 0; s < t.sections.length; s++) { for (var q = 0; q < t.sections[s].questions.length; q++) { qs[t.sections[s].questions[q].q] = 1; } }
      qsets[f] = qs;
    }
    var used = {};
    var items = mp.items || [];
    for (i = 0; i < items.length; i++) {
      var it = items[i], tag = 'item ' + (i + 1);
      var tt = byform[it.form], o = obs[it.obs];
      if (!tt) { errors.push(tag + ': form not in templates: ' + it.form); continue; }
      if (!qsets[it.form][it.q]) { errors.push(tag + ': question ' + it.q + ' not in ' + it.form); continue; }
      if (!o) { errors.push(tag + ': observation ' + it.obs + ' not in inspection'); continue; }
      var fields = ['comment', 'subject', 'action'];
      for (k = 0; k < fields.length; k++) { if (!trim(it[fields[k]])) { errors.push(tag + ': empty ' + fields[k]); } }
      used[o.no] = 1;
      var sel = [];
      if (it.photos == null) { sel = (o.photos || []).slice(0); }
      else {
        var bad = false;
        for (k = 0; k < it.photos.length; k++) { var p = (o.photos || [])[it.photos[k] - 1]; if (p === undefined || it.photos[k] < 1) { bad = true; } else { sel.push(p); } }
        if (bad) { errors.push(tag + ': bad photo index'); continue; }
      }
      if (!tt.items[it.q]) { tt.items[it.q] = []; tt._order.push(it.q); }
      var cur = tt.items[it.q], dup = false;
      for (k = 0; k < cur.length; k++) { if (cur[k].obs === o.no) { dup = true; } }
      if (dup) { errors.push(tag + ': observation ' + o.no + ' placed twice on ' + tt.form + ' ' + it.q); continue; }
      cur.push({ obs: o.no, note: o.note || '', comment: trim(it.comment), subject: trim(it.subject), action: trim(it.action),
        remark: trim(it.remark), photos: sel });
    }
    /* links: same group of observations everywhere, once per framework */
    var perObs = {}, ti, qq;
    for (ti = 0; ti < templates.length; ti++) {
      for (qq = 0; qq < templates[ti]._order.length; qq++) {
        var qn = templates[ti]._order[qq], lst = templates[ti].items[qn], grp = [];
        for (k = 0; k < lst.length; k++) { grp.push(lst[k].obs); }
        grp.sort(function (a, b) { return a - b; });
        for (k = 0; k < lst.length; k++) { (perObs[lst[k].obs] = perObs[lst[k].obs] || []).push([templates[ti].form, qn, grp]); }
      }
    }
    var keys = []; for (k in perObs) { keys.push(+k); } keys.sort(function (a, b) { return a - b; });
    for (i = 0; i < keys.length; i++) {
      var places = perObs[keys[i]], g0 = places[0][2].join(','), diff = false, fws = { OVID: 0, INSPECTARE: 0 };
      for (k = 0; k < places.length; k++) {
        if (places[k][2].join(',') !== g0) { diff = true; }
        fws[places[k][0].indexOf('OVID') === 0 ? 'OVID' : 'INSPECTARE']++;
      }
      if (diff) {
        var desc = []; for (k = 0; k < places.length; k++) { desc.push(places[k][0] + ' ' + places[k][1] + ' = [' + places[k][2].join(', ') + ']'); }
        errors.push('observation ' + keys[i] + ' is grouped differently (link broken): ' + desc.join('; '));
      }
      if (fws.OVID > 1) { errors.push('observation ' + keys[i] + ' is placed ' + fws.OVID + ' times in OVID checklists (place it once per framework)'); }
      if (fws.INSPECTARE > 1) { errors.push('observation ' + keys[i] + ' is placed ' + fws.INSPECTARE + ' times in INSPECTARE checklists (place it once per framework)'); }
    }
    /* one finding per observation */
    for (ti = 0; ti < templates.length; ti++) {
      var T = templates[ti];
      for (qq = 0; qq < T._order.length; qq++) {
        var qk = T._order[qq];
        var L = T.items[qk].slice(0).sort(function (a, b) { return a.obs - b.obs; });
        var first = L[0];
        var item = { comment: first.comment, subject: first.subject, action: first.action, remark: '', notes: [], photos: [] };
        for (k = 0; k < L.length; k++) {
          var x = L[k];
          if (x.remark) { item.remark = (item.remark ? item.remark + ' ' : '') + 'Obs ' + x.obs + ': ' + x.remark; }
          item.notes.push({ obs: x.obs, text: x.note });
          var ph = [];
          for (var m = 0; m < x.photos.length; m++) {
            var d = base(x.photos[m]);
            if (item.photos.indexOf(d) < 0) { item.photos.push(d); }
            ph.push(item.photos.indexOf(d));
          }
          (T.obsList = T.obsList || []).push({ obs: x.obs, q: qk, note: x.note, comment: x.comment, subject: x.subject,
            action: x.action, remark: x.remark, ph: ph });
        }
        if (L.length > 1) {
          item.extra = [];
          for (k = 1; k < L.length; k++) { item.extra.push({ obs: L[k].obs, comment: L[k].comment, subject: L[k].subject, action: L[k].action }); }
        }
        T.items[qk] = item;
      }
    }
    var unassigned = [], ua = mp.unassigned || [];
    for (i = 0; i < ua.length; i++) {
      var uo = obs[ua[i].obs];
      if (!uo) { errors.push('unassigned: observation ' + ua[i].obs + ' not in inspection'); continue; }
      used[uo.no] = 1;
      var uph = []; for (k = 0; k < (uo.photos || []).length; k++) { uph.push(base(uo.photos[k])); }
      unassigned.push({ obs: uo.no, note: uo.note || '', reason: ua[i].reason || '', photos: uph });
    }
    var missing = []; for (i = 0; i < obsNos.length; i++) { if (!used[obsNos[i]]) { missing.push(obsNos[i]); } }
    if (missing.length) { errors.push('observations not mapped and not listed as unassigned: [' + missing.join(', ') + ']'); }
    if (errors.length) { return { errors: errors }; }
    for (ti = 0; ti < templates.length; ti++) { delete templates[ti]._order; }
    var meta = { vessel: insp.vesselName, date: insp.inspectionDate, inspector: mp.inspector || insp.inspector || '',
      location: insp.location || '', tag: mp.synergiTag || 'TEPA DP NAV-DP1' };
    var forms = []; for (ti = 0; ti < templates.length; ti++) { forms.push(templates[ti].form); }
    return { data: { id: meta.vessel + '|' + meta.date + '|' + forms.join('+') + '|' + hash(JSON.stringify(R.mapping || {})),
      meta: meta, templates: templates, unassigned: unassigned } };
  }

  function esc(s) { return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;'); }
  function show() {
    var R = window.TEPA_REPORT, res;
    try { res = R ? build(R) : { errors: ['window.TEPA_REPORT is missing in this file'] }; }
    catch (e) { res = { errors: ['report data could not be read: ' + e.message] }; }
    var html;
    if (res.errors) {
      html = '<!DOCTYPE html><html><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Report errors</title></head>' +
        '<body style="font-family:Arial,sans-serif;padding:16px;color:#1a2a3a"><h2 style="color:#8a2b1f">The report could not be built</h2>' +
        '<p>Copy this list and send it to your AI assistant, asking it to correct the report file:</p><ul>';
      for (var i = 0; i < res.errors.length; i++) { html += '<li>' + esc(res.errors[i]) + '</li>'; }
      html += '</ul></body></html>';
    } else {
      html = TEMPLATE.replace('__REVIEW_DATA__', JSON.stringify(res.data).replace(/<\//g, '<\\/'));
    }
    document.open(); document.write(html); document.close();
  }
  window.TEPA_LOADER = { build: build };
  if (typeof document !== 'undefined' && window.TEPA_REPORT) {
    if (document.readyState === 'complete') { setTimeout(show, 0); } else { window.addEventListener('load', show); }
  }
})();
"""
js = JS.replace('__CHECKLISTS__', json.dumps(checklists, ensure_ascii=True, separators=(',', ':'))) \
       .replace('__TEMPLATE__', json.dumps(template, ensure_ascii=True).replace('</', '<\\/'))
open(os.path.join(repo, 'review-loader.js'), 'w', encoding='utf-8').write(js)
print('review-loader.js', len(js) // 1024, 'KB; checklists.txt', os.path.getsize(os.path.join(repo, 'checklists.txt')) // 1024, 'KB')
