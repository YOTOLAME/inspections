#!/usr/bin/env python3
"""Generate report_kit.py (single self-contained file: builder + review template + all checklists).
Usage: python3 -I tools/make_kit.py <repo dir>   -> writes <repo>/report_kit.py"""
import json, os, sys
repo = sys.argv[1]
tools = os.path.join(repo, 'tools')
sys.path.insert(0, tools)
import build_checklists
tmp = os.path.join(tools, '.kit.tmp.json')
build_checklists.main(repo, tmp)
checklists = open(tmp, encoding='utf-8').read(); os.remove(tmp)
template = open(os.path.join(tools, 'review_template.html'), encoding='utf-8').read()
src = open(os.path.join(tools, 'build_review.py'), encoding='utf-8').read()
a = 'EMBEDDED_CHECKLISTS = None   # filled in report_kit.py'
b = 'EMBEDDED_TEMPLATE = None     # filled in report_kit.py'
assert src.count(a) == 1 and src.count(b) == 1
src = src.replace(a, 'EMBEDDED_CHECKLISTS = ' + json.dumps(checklists))
src = src.replace(b, 'EMBEDDED_TEMPLATE = ' + json.dumps(template))
src = src.replace('"""Build the inspection review HTML', '"""REPORT KIT (generated by tools/make_kit.py, do not edit). Build the inspection review HTML', 1)
open(os.path.join(repo, 'report_kit.py'), 'w', encoding='utf-8').write(src)
print('report_kit.py', len(src) // 1024, 'KB')
